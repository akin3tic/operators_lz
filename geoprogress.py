b,q,n = map(int, input("введите значение первого элемента прогрессии b, множитель прогрессии q и номер последнего элемента n. ").split()) #ввод 3 переменных в строчку
if b>=-10000 and b<=10000 and q>=1 and q<=50 and n>=2 and n<=100: #проверка переменных на выполнение условий задачи
    print("сумма геометрической прогрессии: ", int((b*(1-q**n))/(1-q))) #вывод суммы геометрической прогресии
else:
    print("ошибка переменной") #вывод ошибки если хоть одна из переменных не проходит по значению