c = 0 #присваивание счетчику операций значение 0
n = int(input("введите число n ")) #ввод числа n
if n>=1 and n<=100000: #проверка числа n на услови задачи
    while n !=0: #цикл работает до тех пор пока n не будет равен нулю
        n -=3 #операция с числом n
        c +=1 #прибавление счетчика за каждую операцию
    print("число операций ",c) #вывод числа операций
else:
    print("n не отвечает условиям задачи") #выводит если n не отвечает условиям
